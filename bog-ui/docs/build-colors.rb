# encoding: utf-8
# BOG UI — builds the colour tokens from docs/colors-source.txt (values read from the Figma
# "Mobile Tokens" file, collection "Colors"):
#   tokens-colors.css   Retail Light on :root, then the dark block and one block per brand theme
#   docs/colors.js      the same tokens for the Tokens page (window.BOG_COLORS)
# Run from the bog-ui folder:  ruby docs/build-colors.rb
#
# Themes switch with two attributes on <html>:
#   data-theme="dark"                light (default) / dark
#   data-bog-theme="business"        retail (default) | business | solo | wealth | express-lombard
# docs/theme.js sets both from the docs switchers; prototypes can set them by hand.

root = File.expand_path("..", __dir__)
src = File.read(File.join(root, "docs/colors-source.txt"), encoding: "utf-8")

def css_name(figma)
  "--" + figma.strip.sub(/\A_/, "").downcase.gsub("&", "and").gsub(/[^a-z0-9]+/, "-").gsub(/\A-|-\z/, "")
end

base = []            # [figma, light, dark]
themes = {}          # "business light" => { figma => hex }
section = nil
src.each_line do |line|
  line = line.chomp
  next if line.strip.empty? || line.start_with?("# ")
  if line.start_with?("## ")
    section = line[3..].strip
    themes[section] = {}
    next
  end
  name, value = line.split("=", 2)
  next unless value
  if section
    themes[section][name] = value.strip
  else
    l, d = value.split(",").map(&:strip)
    base << [name, l, d]
  end
end
known = base.map(&:first)
themes.each { |t, h| h.each_key { |n| abort "#{t}: #{n} isn't in the base list" unless known.include?(n) } }

group_of = ->(figma) { figma.sub(/\A_/, "").split("/").first }
out = []
out << "/* =========================================================================="
out << "   BOG UI — colour tokens (GENERATED by docs/build-colors.rb from docs/colors-source.txt — don't edit)"
out << "   Source: Figma \"Mobile Tokens\" (xIoWkxol7tRtpXpPUBLpby), collection Colors, read 2026-11-10."
out << "   #{base.size} tokens. Retail Light is the default; the blocks below switch them:"
out << "     <html data-theme=\"dark\">                 dark mode"
out << "     <html data-bog-theme=\"business\">         retail (default) | business | solo | wealth | express-lombard"
out << "   Names follow Figma: Text/primary → --text-primary, Layer/alpha_pressed_01 → --layer-alpha-pressed-01."
out << "   ========================================================================== */"
out << ""
out << ":root {"
last = nil
base.each do |f, l, _|
  g = group_of.(f)
  out << "  /* #{g} */" if g != last
  last = g
  out << "  #{css_name(f)}: #{l};"
end
out << "  /* Older names still used by components — they follow the tokens above */"
out << "  --avatar-background: var(--avatar-purple-layer-01);"
out << "  --avatar-leyer: var(--avatar-purple-layer-02);"
out << "  --border-selected-neutral: var(--border-selected-neutral-strong);"
out << "}"
out << ""
out << "/* Dark (Retail Dark): only the tokens that change */"
out << ":root[data-theme=\"dark\"] {"
out << "  color-scheme: dark;"
base.each { |f, l, d| out << "  #{css_name(f)}: #{d};" if d != l }
out << "}"
%w[business solo wealth express-lombard].each do |brand|
  pretty = brand.split("-").map(&:capitalize).join(" ")
  { "light" => ":not([data-theme=\"dark\"])", "dark" => "[data-theme=\"dark\"]" }.each do |mode, sel|
    diffs = themes["#{brand} #{mode}"] || {}
    next if diffs.empty?
    out << ""
    out << "/* #{pretty} #{mode.capitalize}: differences from Retail #{mode.capitalize} */"
    out << ":root[data-bog-theme=\"#{brand}\"]#{sel} {"
    base.each { |f, _, _| out << "  #{css_name(f)}: #{diffs[f]};" if diffs[f] }
    out << "}"
  end
end
File.write(File.join(root, "tokens-colors.css"), out.join("\n") + "\n")

# ---- docs/colors.js ---------------------------------------------------------------
groups = []
base.each do |f, l, d|
  g = group_of.(f)
  groups << { "name" => g, "tokens" => [] } if groups.empty? || groups.last["name"] != g
  groups.last["tokens"] << [f.strip, css_name(f), l, d]
end
js = []
js << "/* BOG UI — colour tokens for the Tokens page (GENERATED by docs/build-colors.rb — don't edit)."
js << "   Each token: [Figma name, CSS variable, Retail Light, Retail Dark]. */"
js << "window.BOG_COLORS = {"
js << "  themes: [[\"retail\", \"Retail\"], [\"business\", \"Business\"], [\"solo\", \"SOLO\"], [\"wealth\", \"Wealth\"], [\"express-lombard\", \"Express Lombard\"]],"
js << "  groups: ["
js << groups.map { |g|
  "    { name: #{g["name"].inspect}, tokens: [\n" + g["tokens"].map { |t| "      [" + t.map(&:inspect).join(", ") + "]" }.join(",\n") + "\n    ] }"
}.join(",\n")
js << "  ]"
js << "};"
File.write(File.join(root, "docs/colors.js"), js.join("\n") + "\n")
puts "#{base.size} tokens · groups: #{groups.size} · themes: #{themes.keys.join(", ")}"
